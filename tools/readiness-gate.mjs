#!/usr/bin/env node
/* Clean Core readiness gate + generated matrix.
   Runs `abap-mcp readiness` (offline, abaplint-based, SAP released-API snapshot) over src/, fails when the
   number of ABAP Cloud blockers grows beyond docs/readiness-baseline.json, and rewrites
   docs/clean-core-readiness.generated.md so the per-module evidence is produced, not hand-maintained.
   Usage: node tools/readiness-gate.mjs [--update-baseline] [--edition btp|s4hc|pce] */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const args = process.argv.slice(2);
const edition = args.includes("--edition") ? args[args.indexOf("--edition") + 1] : "btp";
const update = args.includes("--update-baseline");
const BASELINE = "docs/readiness-baseline.json";
const OUT = "docs/clean-core-readiness.generated.md";

let raw;
try {
  raw = execFileSync("npx", ["--yes", "abap-mcp@0.12.7", "readiness", "src", "--edition", edition, "--json"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] });
} catch (e) { raw = e.stdout || ""; }
const start = raw.indexOf("{");
if (start < 0) { console.error("abap-mcp readiness produced no JSON"); process.exit(2); }
const r = JSON.parse(raw.slice(start));

const mod = (file) => file.replace(/\.(clas|prog|intf)\..*$/, "").replace(/^(zcl|zif|zcx|zau)_au_|^zau_/, "");
const perModule = {};
for (const c of r.categories || []) for (const f of c.findings || []) {
  const m = mod(f.file); (perModule[m] ||= { blockers: [], apis: [] });
  perModule[m].blockers.push(`${f.rule} (${c.label}) line ${f.line}: ${(f.excerpt || f.message || "").trim().slice(0, 80)}`);
}
for (const f of r.releasedApiFindings || []) {
  const m = mod(f.file); (perModule[m] ||= { blockers: [], apis: [] });
  perModule[m].apis.push(`${f.object} (${f.objectType}) ${f.state}${f.successor ? ` → ${f.successor}` : ""}`);
}
const blockers = r.cloudBlockerCount ?? 0;
const apis = (r.releasedApiFindings || []).length;

let md = `# Clean Core readiness — generated\n\n`;
md += `Generated by \`node tools/readiness-gate.mjs\` (abap-mcp readiness, edition **${edition}**, released-API snapshot ${r.releasedApiSnapshotDate || "?"}). Do not edit by hand; the hand-written narrative lives in [clean-core-readiness.md](clean-core-readiness.md).\n\n`;
md += `| Verdict | Grade | Cloud blockers | Non-released API uses | Files |\n|---|---|---:|---:|---:|\n| ${r.verdict} | ${r.grade} | ${blockers} | ${apis} | ${r.fileCount} |\n\n`;
md += `Modules with no findings are cloud-syntax clean *as far as static analysis can tell*; ATC \`CLOUD_READINESS\` on the target system remains the final proof.\n\n`;
md += `| Module | ABAP Cloud blockers | Non-released APIs (successor) |\n|---|---|---|\n`;
for (const m of Object.keys(perModule).sort()) {
  const p = perModule[m];
  md += `| \`${m}\` | ${p.blockers.length ? p.blockers.map((b) => `• ${b}`).join("<br>") : "–"} | ${p.apis.length ? [...new Set(p.apis)].map((a) => `• ${a}`).join("<br>") : "–"} |\n`;
}
writeFileSync(OUT, md);
console.log(`readiness: verdict=${r.verdict} grade=${r.grade} blockers=${blockers} nonReleasedApiUses=${apis} → ${OUT}`);

if (update || !existsSync(BASELINE)) {
  writeFileSync(BASELINE, JSON.stringify({ edition, cloudBlockerCount: blockers, nonReleasedApiUses: apis, updatedAt: new Date().toISOString().slice(0, 10) }, null, 2) + "\n");
  console.log(`baseline written to ${BASELINE}`);
  process.exit(0);
}
const b = JSON.parse(readFileSync(BASELINE, "utf8"));
if (blockers > b.cloudBlockerCount || apis > b.nonReleasedApiUses) {
  console.error(`✗ readiness regressed: blockers ${b.cloudBlockerCount} → ${blockers}, non-released API uses ${b.nonReleasedApiUses} → ${apis}. Fix, or run with --update-baseline and justify in the PR.`);
  process.exit(1);
}
console.log(`✓ within baseline (blockers ≤ ${b.cloudBlockerCount}, non-released API uses ≤ ${b.nonReleasedApiUses})`);
